export const normalizeGen1MoveId = (moveId: string) => {
  const normalized = moveId.toLowerCase().replace(/[^a-z0-9?]/g, "");
  return normalized === "vicegrip" ? "visegrip" : normalized;
};

export const getGen1PokemonTypes = (id: number, modernTypes: string[]) => {
  // Clefairy and Clefable were Normal before Fairy existed. For the other
  // original species, removing post-Gen-I Fairy/Steel additions restores R/B typing.
  if (id === 35 || id === 36) return ["normal"];
  return modernTypes.filter((type) => type !== "fairy" && type !== "steel");
};

const GEN1_PHYSICAL_TYPES = new Set([
  "normal",
  "fighting",
  "flying",
  "poison",
  "ground",
  "rock",
  "bug",
  "ghost",
]);

export const getGen1MoveMetadata = (move: MoveMetadata): MoveMetadata => {
  const data = GEN1_MOVE_DATA[normalizeGen1MoveId(move.id)];
  if (!data) return move;

  return {
    ...move,
    accuracy: data.accuracy,
    power: data.power === 0 ? null : data.power,
    pp: data.pp,
    priority: data.priority,
    type: data.type,
    damageClass:
      data.power === 0
        ? "status"
        : GEN1_PHYSICAL_TYPES.has(data.type)
        ? "physical"
        : "special",
  };
};
